export const STRINGS = { ru, en };
export const LANGS = ['ru', 'en'];

export function pluralIndex(lang, n) {
  const a = Math.abs(n);
  if (lang !== 'ru') return a === 1 ? 0 : 1;
  const m10 = a % 10, m100 = a % 100;
  if (m10 === 1 && m100 !== 11) return 0;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 1;
  return 2;
}

// t('ru', 'count.guides', {n: 5}) -> '5 инструкций'. Unknown keys fall back to Russian, then the key.
export function t(lang, key, vars) {
  let s = STRINGS[lang]?.[key] ?? ru[key] ?? key;
  if (Array.isArray(s)) s = s[Math.min(pluralIndex(lang, vars?.n ?? 0), s.length - 1)];
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

// Bound translator, the form widgets get as ctx.t.
export function translator(lang) {
  return (key, vars) => t(lang, key, vars);
}

// Alert titles for the Markdown renderer: {note, tip, important, warning, caution}.
export function alertLabels(lang) {
  const out = {};
  for (const k of ['note', 'tip', 'important', 'warning', 'caution']) out[k] = t(lang, 'alert.' + k);
  return out;
}

export function formatDate(lang, iso) {
  if (!iso) return '';
  const d = new Date(String(iso).slice(0, 10) + 'T12:00:00Z');
  if (Number.isNaN(d.getTime())) return String(iso);
  return new Intl.DateTimeFormat(lang === 'en' ? 'en-GB' : 'ru-RU', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(d);
}

export function formatMinutes(lang, n) {
  if (n < 60) return t(lang, 'unit.min', { n });
  const h = Math.floor(n / 60), m = n % 60;
  return m ? t(lang, 'unit.hours', { h, m }) : t(lang, 'unit.hoursOnly', { h });
}
